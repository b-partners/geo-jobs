class ZoneGeometryRealZonesTest {
  static final List<String> ZONES =
      List.of(
          "[[[-0.24942892774653336,46.65204181284632],[-0.2494634701833243,46.65196258378066],[-0.24929918298397974,46.65193251140419],[-0.24925284556877483,46.65195853557712],[-0.24924105059036086,46.65200190917084],[-0.24932614293463165,46.652027933310364],[-0.24942892774653336,46.65204181284632]]]",
          "[[[-0.24942808524808235,46.65204412610196],[-0.24946178518640233,46.65196547535444],[-0.24935310288530357,46.65194754759451],[-0.24929328549476273,46.651931933089095],[-0.24925284556877483,46.651959692206745],[-0.24923852309498787,46.65200190917084],[-0.24932361543925868,46.652027933310364],[-0.24942808524808235,46.65204412610196]]]",
          "[[[-0.24942977024498442,46.652048752612956],[-0.24946852517407028,46.65195390905839],[-0.2493581578760496,46.65194696927959],[-0.24929665548860672,46.651931933089095],[-0.24924947557493085,46.65196258378066],[-0.24923936559343887,46.65200248748517],[-0.2493244579377097,46.65202619836811],[-0.24942977024498442,46.652048752612956]]]",
          "[[[-0.24943229774037734,46.65204412610196],[-0.2494626276848733,46.651964897039704],[-0.24936574036216858,46.651945234334754],[-0.24929581299013576,46.651933089719286],[-0.24925537306414786,46.651956800632654],[-0.24924105059036086,46.65200190917084],[-0.24932614293463165,46.652027933310364],[-0.24943229774037734,46.65204412610196]]]",
          "[[[-0.24942808524808235,46.65204354778806],[-0.2494634701833243,46.6519660536692],[-0.24929328549476273,46.65193251140419],[-0.24925284556877483,46.651959692206745],[-0.24924105059036086,46.652001330856486],[-0.24932530043618065,46.652026776682185],[-0.24942808524808235,46.65204354778806]]]");

  @Test
  void every_pair_of_hand_drawn_zones_of_the_same_building_is_similar_by_default() {
    var conf = ZoneSimilarityConf.defaults();
    for (int i = 0; i < ZONES.size(); i++) {
      for (int j = 0; j < ZONES.size(); j++) {
        var a = zone(ZONES.get(i));
        var b = zone(ZONES.get(j));

        var iou = a.iouWith(b);

        assertTrue(iou >= conf.getMinIou(), "iou of zones " + i + " and " + j + " is " + iou);
        assertTrue(
            a.isWithinDisplacementOf(b, conf.getMaxDisplacementInMeters()),
            "zones " + i + " and " + j + " are too far apart");
      }
    }
  }

  private static ZoneGeometry zone(String coordinates) {
    return ZoneGeometry.ofIndividual(
            List.of(
                Feature.builder()
                    .geometry(
                        Feature.FeatureGeometry.builder()
                            .actualInstanceStringValue(
                                "{\"type\":\"Polygon\",\"coordinates\":" + coordinates + "}")
                            .build())
                    .build()))
        .orElseThrow();
  }
}
